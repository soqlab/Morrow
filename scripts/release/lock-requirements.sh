#!/bin/sh
# Regenerates the hashed lock files from the hand-edited requirement files:
#
#   backend/requirements.txt                       -> backend/requirements.lock
#   backend/requirements.txt + requirements-dev.txt -> backend/requirements-dev.lock
#   backend/requirements-bootstrap.txt             -> backend/requirements-bootstrap.lock
#   scripts/release/sbom-tools.txt                 -> scripts/release/sbom-tools.lock
#
# The images install the .lock files with `pip install --require-hashes --no-deps`, so every
# package, transitives included, is the exact file whose sha256 is written here. Run this after
# changing any of the .txt files, from anywhere in the repository (needs Docker, and internet):
#
#   sh scripts/release/lock-requirements.sh
#
# It resolves for Linux x86_64 and CPython 3.11, the platform the images run, inside the pinned
# Python image, so the result does not depend on the machine you run it on. Resolution takes the
# newest release of each unpinned transitive dependency, so running it again later can move those;
# review the diff like any dependency upgrade.
set -eu
root="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$root"
. scripts/release/pins.sh

# Inputs go in on stdin and the locks come back on stdout, as a tar, so this works the same with a
# remote Docker daemon, from a container, or on Windows (no bind mount).
tar -cf - backend/requirements.txt backend/requirements-dev.txt backend/requirements-bootstrap.txt \
    scripts/release/sbom-tools.txt \
  | docker run --rm -i --network bridge -e UV_VERSION="$UV_VERSION" "$PYTHON_IMAGE" sh -euc '
      mkdir /w && cd /w && tar -xf -
      pip install --quiet --no-cache-dir --disable-pip-version-check --root-user-action=ignore \
        "uv==$UV_VERSION" >&2
      compile() {
        out="$1"; shift
        uv pip compile --quiet --generate-hashes --no-header --emit-index-url \
          --python-version 3.11 --python-platform x86_64-manylinux_2_28 --only-binary :all: \
          "$@" -o "$out" >&2
      }
      compile backend/requirements.lock backend/requirements.txt
      compile backend/requirements-dev.lock backend/requirements.txt backend/requirements-dev.txt
      compile backend/requirements-bootstrap.lock backend/requirements-bootstrap.txt
      compile scripts/release/sbom-tools.lock scripts/release/sbom-tools.txt
      tar -cf - backend/*.lock scripts/release/*.lock
    ' \
  | tar -xf -

for f in backend/requirements.lock backend/requirements-dev.lock \
         backend/requirements-bootstrap.lock scripts/release/sbom-tools.lock; do
  # Header naming the source and the command, so nobody edits a lock by hand.
  { echo "# Generated by scripts/release/lock-requirements.sh; do not edit by hand."
    echo "# Linux x86_64, CPython 3.11, wheels only. Install with:"
    echo "#   pip install --require-hashes --only-binary :all: --no-deps -r $(basename "$f")"
    cat "$f"; } > "$f.tmp"
  mv "$f.tmp" "$f"
  echo "wrote $f ($(grep -c '==' "$f") packages)"
done
