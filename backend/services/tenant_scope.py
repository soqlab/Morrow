"""Which tenant a Postgres connection is allowed to see, and the audited way to step outside it.

Why this module exists
----------------------
Tenant isolation used to rest entirely on ``WHERE organization_id = ?`` in every query. Postgres
row-level security turns that convention into an enforced boundary, but a policy can only be as good
as the value it reads. This module owns that value.

Two session settings (GUCs) carry the decision to Postgres:

``app.current_organization_id``
    The tenant whose rows the connection may read and write. Policies generated by
    services/postgres_rls.py compare it against each row's ``organization_id``. An empty or unset
    value matches *nothing* -- deliberately, including rows whose organization_id is itself the empty
    string (the anonymous-traffic bucket). "No tenant resolved" must never mean "some rows".

``app.platform_scope``
    ``'on'`` only while the process is executing an explicitly privileged operation: a vendor-operator
    endpoint that authenticated against the platform credential, or a background writer that works
    across every tenant by design. Policies treat it as a second, disjunctive branch, so the escape
    hatch is visible in the policy text rather than hidden in a role attribute.

Why a session flag rather than BYPASSRLS
----------------------------------------
A role with BYPASSRLS is exempt from every policy on every statement, forever, with no record that
the exemption was used. A session flag has to be turned on by a named code path, is off again the
moment that path returns, and can be counted and logged -- see ``platform_scope()``, which records
every entry. The application role stays NOSUPERUSER NOBYPASSRLS so the policies remain the only way
in, and this flag is the only door.

Leak safety on a pooled connection
----------------------------------
Both settings are written on *every* connection checkout (``apply_to_connection``) and RESET on every
release (``reset_on_release``). Writing on checkout is what makes reuse safe: the borrower's values
overwrite whatever the previous borrower left, so a connection cannot serve tenant B while still
carrying tenant A. The RESET on release is defence in depth -- an idle pooled connection carries no
tenant at all, so anything that ever reaches one outside this module's checkout path sees nothing
rather than someone else's data. Session scope (``is_local=False``) is used rather than ``SET LOCAL``
because several callers commit part-way through a ``with pg_product_conn()`` block; a transaction-local
setting would vanish at that commit and the rest of the block would silently read zero rows.

SQLite
------
Everything here is a no-op on SQLite: ``apply_to_connection``/``reset_on_release`` are only ever
handed psycopg2 connections, and the scope context managers are pure Python state that a SQLite
backend simply never reads.
"""

from __future__ import annotations

import contextvars
import logging
import threading
import time
from contextlib import contextmanager
from typing import Any, Callable, Dict, Iterator, List, Optional

logger = logging.getLogger(__name__)

#: Name of the Postgres setting carrying the tenant. Must match services/postgres_rls.ORG_SETTING.
ORG_SETTING = "app.current_organization_id"

#: Name of the Postgres setting carrying the platform-operator escape hatch.
PLATFORM_SETTING = "app.platform_scope"

#: Value that turns the escape hatch on. Anything else (including unset) leaves it off.
PLATFORM_ON = "on"

_SCOPE: contextvars.ContextVar[Optional[Dict[str, str]]] = contextvars.ContextVar(
    "pqc_platform_scope", default=None
)

_LOCK = threading.Lock()
_ESCAPE_LOG: List[Dict[str, Any]] = []
_ESCAPE_LOG_MAX = 200
_ESCAPE_COUNT = 0

#: Optional sink the application installs so escape-hatch use also lands in the durable operator
#: audit trail. Kept as a hook rather than a hard import because this module is imported by the
#: database layer, which must not depend on the application's audit machinery.
_audit_sink: Optional[Callable[[Dict[str, Any]], None]] = None


def set_audit_sink(sink: Optional[Callable[[Dict[str, Any]], None]]) -> None:
    """Install (or clear) a callback that receives every platform-scope entry."""
    global _audit_sink
    _audit_sink = sink


# --------------------------------------------------------------------------- #
# Scope state
# --------------------------------------------------------------------------- #

def is_platform_scope() -> bool:
    """True while the caller is inside an explicitly privileged, cross-tenant operation."""
    return bool(_SCOPE.get())


def current_scope() -> Dict[str, str]:
    """Describe the active scope, for diagnostics and tests."""
    active = _SCOPE.get()
    if not active:
        return {"scope": "tenant", "reason": "", "actor": ""}
    return {"scope": "platform", "reason": active.get("reason", ""), "actor": active.get("actor", "")}


def _record(reason: str, actor: str) -> Dict[str, Any]:
    global _ESCAPE_COUNT
    entry = {
        "at": time.time(),
        "reason": str(reason or "unspecified")[:160],
        "actor": str(actor or "")[:120],
    }
    with _LOCK:
        _ESCAPE_COUNT += 1
        _ESCAPE_LOG.append(entry)
        if len(_ESCAPE_LOG) > _ESCAPE_LOG_MAX:
            del _ESCAPE_LOG[: len(_ESCAPE_LOG) - _ESCAPE_LOG_MAX]
    # Logged at INFO, not DEBUG: crossing the tenant boundary is a security-relevant event and an
    # operator reading the logs should be able to see every one of them without raising the level.
    logger.info("[PQC RLS] cross-tenant scope entered: reason=%s actor=%s", entry["reason"], entry["actor"] or "-")
    sink = _audit_sink
    if sink is not None:
        try:
            sink(dict(entry))
        except Exception:
            # An audit sink that fails must not break the operator request it is describing; the
            # in-process ledger and the log line above still record the event.
            logger.warning("[PQC RLS] platform-scope audit sink failed", exc_info=False)
    return entry


def enter_platform_scope(reason: str, actor: str = "") -> None:
    """Turn the escape hatch on for the remainder of the current context, and audit it.

    Used by request handlers, where the request's context is discarded when the response is sent, so
    there is nothing to unwind. Background code should prefer ``platform_scope()``, which restores
    the previous scope on exit.
    """
    entry = _record(reason, actor)
    _SCOPE.set({"reason": entry["reason"], "actor": entry["actor"]})


@contextmanager
def platform_scope(reason: str, actor: str = "") -> Iterator[None]:
    """Run a block with cross-tenant access, then put the scope back exactly as it was.

    Every entry is audited. Use the narrowest block that does the job: while this is on, RLS is not
    isolating anything for connections checked out inside it.
    """
    entry = _record(reason, actor)
    token = _SCOPE.set({"reason": entry["reason"], "actor": entry["actor"]})
    try:
        yield
    finally:
        try:
            _SCOPE.reset(token)
        except ValueError:
            # The block spanned a context boundary (e.g. a thread handoff); fall back to clearing.
            _SCOPE.set(None)


@contextmanager
def tenant_scope() -> Iterator[None]:
    """Force ordinary tenant isolation inside a block, even under an outer platform scope.

    For the operator paths that do serve a single customer's data and should be held to the same
    boundary as that customer.
    """
    token = _SCOPE.set(None)
    try:
        yield
    finally:
        try:
            _SCOPE.reset(token)
        except ValueError:
            _SCOPE.set(None)


def escape_events(limit: int = 50) -> List[Dict[str, Any]]:
    """Most recent platform-scope entries, newest last. Bounded; see _ESCAPE_LOG_MAX."""
    with _LOCK:
        return [dict(e) for e in _ESCAPE_LOG[-int(max(1, limit)):]]


def escape_count() -> int:
    """Total platform-scope entries since process start (the ledger itself is bounded)."""
    return _ESCAPE_COUNT


def reset_audit_log() -> None:
    """Test helper: forget the recorded escapes."""
    global _ESCAPE_COUNT
    with _LOCK:
        _ESCAPE_LOG.clear()
        _ESCAPE_COUNT = 0


# --------------------------------------------------------------------------- #
# Applying the scope to a Postgres connection
# --------------------------------------------------------------------------- #

def current_org_setting_value() -> str:
    """The tenant to publish, or '' when none is resolved (which matches no row)."""
    if is_platform_scope():
        # Under platform scope the org setting is irrelevant to reads, and publishing a stale
        # request-context org would be misleading in pg_stat_activity and in any future audit.
        return ""
    try:
        from db import current_organization_id
        return str(current_organization_id() or "").strip()
    except Exception:
        return ""


def apply_to_connection(conn: Any) -> None:
    """Publish the caller's scope onto a freshly checked-out psycopg2 connection.

    Both settings are written every time, including the empty values, so a checkout never inherits
    what the previous borrower left behind.

    It has to be committed, not merely executed. ``set_config(..., is_local=False)`` is still
    transactional, so a rollback later in the borrow -- an aborted statement, a failed savepoint --
    would otherwise undo the tenant along with the work and leave the rest of the borrow reading
    nothing. Rather than pay a second round trip for an explicit COMMIT, the statement is run in
    autocommit mode and the connection is handed back in its normal transactional state: one round
    trip, no WAL, and the setting pinned for the session.

    Best-effort by design: on a database where the plan has not been applied there are no policies to
    satisfy, and failing to set an advisory GUC must not take the deployment down. Where the plan
    *has* been applied, a failure here means the connection sees nothing, which is the safe direction.
    """
    org = current_org_setting_value()
    platform = PLATFORM_ON if is_platform_scope() else ""
    _write(conn, org, platform)


def _write(conn: Any, org: str, platform: str) -> None:
    previous = getattr(conn, "autocommit", False)
    try:
        conn.autocommit = True
    except Exception:
        # psycopg2 refuses this while a transaction is open. That should not happen -- both callers
        # run on a connection that has just been checked out or just rolled back -- but if it does,
        # the settings still get written; they simply join the caller's transaction instead of being
        # committed on their own. Committing here would silently commit the caller's in-flight work,
        # which is a far worse outcome than a setting that a later rollback could undo.
        previous = None
    try:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT set_config(%s, %s, false), set_config(%s, %s, false)",
                (ORG_SETTING, org, PLATFORM_SETTING, platform),
            )
    except Exception:
        # Leave the caller a clean transaction rather than an aborted one.
        try:
            conn.rollback()
        except Exception:
            pass
    finally:
        if previous is not None:
            try:
                conn.autocommit = previous
            except Exception:
                pass


def reset_on_release(conn: Any) -> None:
    """Clear both settings before the connection goes back to the pool.

    An idle pooled connection then carries no tenant and no privilege, so anything that reaches it
    without going through ``apply_to_connection`` sees nothing instead of the last borrower's data.

    The leading rollback is load-bearing. This runs on the failure path too, where the borrower's
    transaction is aborted and every statement on the connection raises until something rolls it
    back -- so without it the clear would silently fail exactly when it matters most, on the request
    that blew up while holding someone's tenant.
    """
    try:
        conn.rollback()
    except Exception:
        pass
    _write(conn, "", "")
