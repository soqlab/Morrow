def _make_readme(framework: dict, org_id: str, built_at: str) -> str:
    return f"""Morrow — Compliance Evidence Package
==========================================
Framework : {framework['name']}
Org       : {org_id}
Built     : {built_at}
Description: {framework['description']}

Controls covered:
{chr(10).join('  - ' + c for c in framework['controls'])}

Files in this package:
  - README.txt              This file
  - scan_report.json        Latest scan findings (all assets)
  - cbom.json               Cryptographic Bill of Materials
  - fips_compliance.json    FIPS 203/204/205 compliance status
  - compliance_gap.json     Framework gap analysis
  - security_intents.json   Active security policies
  - remediation_progress.json Remediation playbook completion
  - drift_events.json       Crypto drift log (last 90 days)
  - evidence_manifest.json  Hashes of all included files

Generated by Morrow — https://pqcscanner.io
"""


def _sha256_str(s: str) -> str:
    import hashlib
    return hashlib.sha256(s.encode()).hexdigest()


def build_package(
    org_id: str,
    framework_key: str,
    scan_data: Optional[dict] = None,
    cbom_data: Optional[dict] = None,
    fips_data: Optional[dict] = None,
    gap_data: Optional[dict] = None,
    intents_data: Optional[dict] = None,
    remediation_data: Optional[dict] = None,
    drift_data: Optional[dict] = None,
) -> bytes:
    """Build and return a ZIP file as bytes."""
    framework = FRAMEWORKS.get(framework_key, FRAMEWORKS["nist_sp_800_208"])
    built_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    files = {
        "scan_report.json": scan_data or {"note": "No scan data available", "org_id": org_id},
        "cbom.json": cbom_data or {"note": "No CBOM data available", "org_id": org_id},
        "fips_compliance.json": fips_data or {"note": "No FIPS data available"},
        "compliance_gap.json": gap_data or {"note": "No gap analysis available"},
        "security_intents.json": intents_data or {"note": "No security intents found"},
        "remediation_progress.json": remediation_data or {"note": "No remediation data"},
        "drift_events.json": drift_data or {"note": "No drift events"},
    }

    manifest = {}
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        readme = _make_readme(framework, org_id, built_at)
        zf.writestr("README.txt", readme)
        manifest["README.txt"] = _sha256_str(readme)

        for fname, data in files.items():
            content = json.dumps(data, indent=2)
            zf.writestr(fname, content)
            manifest[fname] = _sha256_str(content)

        manifest_content = json.dumps({
            "framework": framework["name"],
            "org_id": org_id,
            "built_at": built_at,
            "file_hashes": manifest,
        }, indent=2)
        zf.writestr("evidence_manifest.json", manifest_content)

    return buf.getvalue()


def list_frameworks() -> list[dict]:
    return [
        {"key": k, "name": v["name"], "description": v["description"],
         "controls": len(v["controls"])}
        for k, v in FRAMEWORKS.items()
    ]
